<h2 class="wp-block-heading">It wasn’t the designs. <em>It was the people.</em></h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>For 14 years, I worked as a fashion designer — moving between fast-paced creative studios and the structure of a corporate environment. Along the way, I lived abroad in Canada for four years, which taught me more than I expected about starting again, feeling lost, and finding my identity in unfamiliar places.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>My first real introduction to coaching came almost by accident. While working as a designer at M&amp;S, I took part in a leadership development programme — and it changed something in me. For the first time, I had space to properly reflect on my thoughts, feelings and behaviours: who I was, what I wanted, where I was headed. It was freeing in a way I hadn’t imagined possible. Not long after, I quit my job and went travelling for six months. That trip was the start of a self-development journey I’ve now been on for eight years.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Years later, after experiencing burnout in my most recent design role, I found myself reflecting on what had actually brought me the most joy in my career. It wasn’t the designs. It was the people — specifically, developing those around me, watching them grow, and being part of that process.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That realisation led me here. What draws me to transformative coaching is the chance to hold space for someone as they explore their feelings and reflections — to sit alongside them, wherever the conversation takes us, and help them uncover what they’re really looking for.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"className":"tgr-signoff"} -->
<p class="tgr-signoff">I know what it feels like to be lost, to start again, and to finally find clarity. I’d love to help you find yours.</p>
