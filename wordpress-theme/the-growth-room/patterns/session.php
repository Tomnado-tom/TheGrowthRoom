<!-- wp:heading {"textAlign":"center","textColor":"cream"} -->
<h2 class="wp-block-heading has-text-align-center has-cream-color has-text-color">A conversation that’s yours to lead.</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"align":"center","fontSize":"large"} -->
<p class="has-text-align-center has-large-font-size">This isn’t advice-giving or problem-solving in the way you might expect. I won’t turn up with an agenda, a framework to push you through, or answers I’ve already decided on. Every conversation is yours to lead — we shape it together, based on whatever’s actually present for you that day.</p>
<!-- /wp:paragraph -->

<!-- wp:columns {"align":"wide","className":"tgr-steps","style":{"spacing":{"margin":{"top":"var:preset|spacing|60"},"blockGap":{"left":"var:preset|spacing|50"}}}} -->
<div class="wp-block-columns alignwide tgr-steps" style="margin-top:var(--wp--preset--spacing--60)"><!-- wp:column {"className":"tgr-step"} -->
<div class="wp-block-column tgr-step"><!-- wp:heading {"level":3,"textColor":"cream"} -->
<h3 class="wp-block-heading has-cream-color has-text-color">Curiosity, not assumptions</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>I try to meet you with real curiosity, not assumptions — which means I won’t pretend to already know your experience. You’re the expert on your own life, not me. A lot of the time, the insight comes from the conversation itself — from being asked a good question, saying something out loud for the first time, or just sitting in a silence that gives you room to think. Nothing’s rushed or forced. We let things unfold naturally rather than following a script.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column -->

<!-- wp:column {"className":"tgr-step"} -->
<div class="wp-block-column tgr-step"><!-- wp:heading {"level":3,"textColor":"cream"} -->
<h3 class="wp-block-heading has-cream-color has-text-color">Deep, but grounded</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>That might look like picking apart a decision from every angle, noticing a pattern you’ve never quite put into words before, or simply sitting with a feeling until you understand what it’s actually telling you. This work goes deep, but it’s not just reflection for its own sake — we’ll always come back to what it actually means for your life, going forward.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column -->

<!-- wp:column {"className":"tgr-step"} -->
<div class="wp-block-column tgr-step"><!-- wp:heading {"level":3,"textColor":"cream"} -->
<h3 class="wp-block-heading has-cream-color has-text-color">Come as you are</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Sessions are confidential and judgement-free. You don’t need to show up with the “right” problem, or even a clear goal. Honestly, some of the best sessions start with “I don’t know why, but something feels off.”</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column --></div>
