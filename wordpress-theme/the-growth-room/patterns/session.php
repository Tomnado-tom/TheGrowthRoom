<p class="has-text-align-center tgr-closing has-cream-color has-text-color" style="margin-top:var(--wp--preset--spacing--70)">I don’t have the answers. What I can do is walk alongside you while you find them yourself — and help you see things not just in this one moment, but in the context of your whole life, your relationships, and the world around you.</p>
